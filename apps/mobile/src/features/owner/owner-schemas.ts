import { z } from 'zod';

const tokenValue = z
  .string()
  .min(43, 'Enter the complete owner token.')
  .max(128, 'Owner token is too long.')
  .regex(/^[A-Za-z0-9_-]+$/, 'Use the token generated by Streak’s secure setup tool.');

export const ownerSetupSchema = z.object({ ownerToken: tokenValue });
export const ownerRotationSchema = z.object({ nextToken: tokenValue });

export type OwnerSetupInput = z.infer<typeof ownerSetupSchema>;
export type OwnerRotationInput = z.infer<typeof ownerRotationSchema>;
